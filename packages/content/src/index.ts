export interface CaregiverCard {
  title: string;
  lines: string[];
  returnTitle: string;
  returnSigns: string[];
  where: string;
  footer: string;
  draft: boolean;
}

export function caregiverCard(lang: Lang, outcome: Decision, symptoms: { cough: boolean | null; diarrhea: boolean | null; difficultyBreathing: boolean | null }, clinicName?: string): CaregiverCard {
  const lines = [t(lang, 'card_medicine')];
  if (outcome === 'GO_NOW') lines.unshift(t(lang, 'card_go_now_travel'));
  else lines.push(t(lang, 'card_home_care'));
  const returnSigns = ['card_return_drink', 'card_return_sicker', 'card_return_fever', 'card_return_convulsions'];
  if (symptoms.cough || symptoms.difficultyBreathing) returnSigns.push('card_return_breathing');
  if (symptoms.diarrhea) returnSigns.push('card_return_blood', 'card_return_drinking_poorly');
  return {
    title: t(lang, `card_title_${outcome}`),
    lines,
    returnTitle: t(lang, 'card_return_title'),
    returnSigns: returnSigns.map((k) => t(lang, k)),
    where: clinicName ?? t(lang, 'card_where_default'),
    footer: t(lang, 'card_footer'),
    draft: TRANSLATION_STATUS[lang] !== 'source',
  };
}

